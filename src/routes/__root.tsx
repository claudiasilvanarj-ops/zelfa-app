function ErrorComponent({ error, reset }: ErrorComponentProps) {
  console.error(error);
  const router = useRouter();
  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-2xl font-semibold text-foreground">Ops, algo não carregou</h1>
        <p className="mt-2 text-muted-foreground">Vamos tentar de novo?</p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="rounded-full bg-primary px-6 py-3 font-bold text-primary-foreground"
          >
            Tentar de novo
          </button>
          <a href="/" className="rounded-full border border-input bg-background px-6 py-3 font-bold text-foreground">
            Início
          </a>
        </div>
      </div>
    </div>
  );
}

